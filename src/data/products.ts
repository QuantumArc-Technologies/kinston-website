// ---------- generators ----------

const r = (n: number, step = 1) => Math.round(n / step) * step;

/** Scale a base dimension set (defined at 1 t) across a list of working load limits. */
function scaled(
  prefix: string,
  wlls: number[],
  base: Record<string, number>,
  baseWeight: number,
  opts: { exp?: number; wexp?: number; codeFrom?: 'wll' | 'index'; extra?: (wll: number, i: number) => SpecRow } = {},
): SpecRow[] {
  const exp = opts.exp ?? 0.42;
  const wexp = opts.wexp ?? 1.25;
  return wlls.map((wll, i) => {
    const f = Math.pow(wll, exp);
    const row: SpecRow = {
      code: `${prefix}-${opts.codeFrom === 'index' ? String(i + 1).padStart(2, '0') : String(wll).replace('.', '')}`,
      wll,
    };
    for (const [k, v] of Object.entries(base)) row[k] = r(v * f, v * f > 40 ? 1 : 0.5);
    row.weight = Math.round(baseWeight * Math.pow(wll, wexp) * 100) / 100;
    if (opts.extra) Object.assign(row, opts.extra(wll, i));
    return row;
  });
}

const G100: Array<[number, number]> = [
  [6, 1.4], [7, 1.9], [8, 2.5], [10, 4], [13, 6.7], [16, 10], [20, 16], [22, 19], [26, 26.5], [32, 40],
];
const G80: Array<[number, number]> = [
  [6, 1.12], [7, 1.5], [8, 2], [10, 3.15], [13, 5.3], [16, 8], [20, 12.5], [22, 15], [26, 21.2], [32, 31.5],
];

/** Chain-size driven rows (chain fittings). */
function chainRows(
  prefix: string,
  grade: 'G100' | 'G80',
  base: Record<string, number>,
  baseWeight: number,
  limit = 8,
): SpecRow[] {
  const table = grade === 'G100' ? G100 : G80;
  return table.slice(0, limit).map(([chain, wll]) => {
    const f = chain / 8; // base dims defined at 8 mm chain
    const row: SpecRow = { code: `${prefix}-${String(chain).padStart(2, '0')}`, chain, wll };
    for (const [k, v] of Object.entries(base)) row[k] = r(v * f, v * f > 40 ? 1 : 0.5);
    row.weight = Math.round(baseWeight * Math.pow(f, 2.9) * 100) / 100;
    return row;
  });
}

