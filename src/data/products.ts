export const productsByCategory = (slug: string) => products.filter((p) => p.category === slug);
export const productBySlug = (slug: string) => products.find((p) => p.slug === slug);
export const featuredProducts = () => products.filter((p) => p.featured);
export const relatedProducts = (p: Product, n = 4) => {
  const sameGroup = products.filter((x) => x.slug !== p.slug && x.category === p.category && x.group === p.group);
  const sameCat = products.filter((x) => x.slug !== p.slug && x.category === p.category && x.group !== p.group);
  return [...sameGroup, ...sameCat].slice(0, n);
};
export const productUrl = (p: Product) => `/products/${p.category}/${p.slug}`;
export const wllRange = (p: Product) => {
  const w = p.specRows.map((r) => Number(r.wll)).filter((n) => !Number.isNaN(n) && n > 0);
  if (!w.length) return null;
  return { min: Math.min(...w), max: Math.max(...w) };
};
export const categoryCount = (slug: string) => productsByCategory(slug).length;
// Hide ranges while their product listings are commented out.
export const allCategoriesWithCounts = () => categories
  .map((c) => {
    const items = productsByCategory(c.slug);
    return {
      ...c,
      count: items.length,
      image: items[0]?.image ?? c.image,
      groups: c.groups.filter((group) => items.some((p) => p.group === group)),
    };
  })
  .filter((c) => c.count > 0);
